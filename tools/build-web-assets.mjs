/**
 * Build the web assets that are embedded in the firmware.
 *
 * Reads the static site (pages, styles, ES modules, catalog JSON), gzips every
 * file and emits a C header with a PROGMEM byte array per asset plus a
 * lookup table the firmware can serve directly with Content-Encoding: gzip.
 *
 * Usage: node tools/build-web-assets.mjs [--min] [--out <path>]
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/markdown; charset=utf-8',
  '.woff2': 'font/woff2',
  '.bin': 'application/octet-stream'
};

/*
 * The device serves the *complete* control panel. The label designer and the
 * maintenance console are the reason a user connects to the board over Wi-Fi,
 * so they ship in every build - ESP32 and ESP8266 alike - together with the
 * docs page (REST API, FAQ) and the installer/help page. `--min` keeps writing
 * the ESP8266 header for the CI matrix; the asset set is identical, the size
 * difference comes from gzip.
 */
const PAGES = ['index.html', 'install.html', 'designer.html', 'troubleshoot.html', 'docs.html'];
const MIN_PAGES = PAGES;
const CORE_JS = [
  'assets/js/core/catalog.js',
  'assets/js/core/wiring.js',
  'assets/js/core/commands.js',
  'assets/js/core/barcode.js',
  'assets/js/core/qr.js',
  'assets/js/core/raster.js',
  'assets/js/core/label.js',
  'assets/js/ui/i18n.js',
  'assets/js/ui/shell.js',
  'assets/js/ui/device.js',
  'assets/js/ui/home.js',
  'assets/js/ui/install.js',
  'assets/js/ui/designer.js',
  'assets/js/ui/troubleshoot.js',
  'assets/js/ui/docs.js'
];
const MIN_JS = CORE_JS;
const DATA = ['data/boards.json', 'data/apps.json'];

function parseArgs(argv) {
  const args = { min: false, out: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--min') args.min = true;
    else if (argv[i] === '--out') args.out = argv[++i];
  }
  return args;
}

function mimeFor(path) {
  const ext = path.slice(path.lastIndexOf('.'));
  return MIME[ext] || 'application/octet-stream';
}

function toCArray(bytes) {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 20) {
    rows.push('  ' + [...bytes.slice(i, i + 20)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', '));
  }
  return rows.join(',\n');
}

export async function buildAssets({ min = false } = {}) {
  const files = [...(min ? MIN_PAGES : PAGES), 'assets/css/app.css', ...(min ? MIN_JS : CORE_JS), ...DATA];
  const assets = [];
  for (const file of files) {
    const raw = await readFile(join(ROOT, file));
    const gz = gzipSync(raw, { level: 9 });
    const useGz = gz.length < raw.length;
    assets.push({
      path: '/' + file.replace(/^\//, ''),
      mime: mimeFor(file),
      data: useGz ? gz : raw,
      original: raw.length,
      gz: useGz
    });
  }
  return assets;
}

export function renderHeader(assets) {
  const lines = [];
  lines.push('// Generated by tools/build-web-assets.mjs - do not edit by hand.');
  lines.push('// Served by the device web server with Content-Encoding: gzip when gz is true.');
  lines.push('#pragma once');
  lines.push('#include <stdint.h>');
  lines.push('#include <stddef.h>');
  lines.push('#if defined(__AVR__)');
  lines.push('#include <avr/pgmspace.h>');
  lines.push('#endif');
  lines.push('#ifndef PROGMEM');
  lines.push('#define PROGMEM');
  lines.push('#endif');
  lines.push('');
  lines.push('struct WebAsset {');
  lines.push('  const char* path;');
  lines.push('  const char* mime;');
  lines.push('  const uint8_t* data;');
  lines.push('  unsigned int len;');
  lines.push('  unsigned int originalLen;');
  lines.push('  bool gz;');
  lines.push('};');
  lines.push('');
  assets.forEach((asset, i) => {
    lines.push(`// ${asset.path} (${asset.original} bytes${asset.gz ? `, ${asset.data.length} gzipped` : ''})`);
    lines.push(`static const uint8_t ARSIN_ASSET_${i}[] PROGMEM = {`);
    lines.push(toCArray(asset.data));
    lines.push('};');
    lines.push('');
  });
  lines.push('static const WebAsset WEB_ASSETS[] PROGMEM = {');
  assets.forEach((asset, i) => {
    lines.push(
      `  { "${asset.path}", "${asset.mime}", ARSIN_ASSET_${i}, ${asset.data.length}u, ${asset.original}u, ${asset.gz ? 'true' : 'false'} },`
    );
  });
  lines.push('};');
  lines.push('');
  lines.push(`static const unsigned int WEB_ASSETS_COUNT = ${assets.length}u;`);
  lines.push('');
  lines.push('// Lookup helper used by the web servers.');
  lines.push('inline const WebAsset* arsinFindAsset(const char* path) {');
  lines.push('  for (unsigned int i = 0; i < WEB_ASSETS_COUNT; i++) {');
  lines.push('    const char* a = WEB_ASSETS[i].path;');
  lines.push('    const char* b = path;');
  lines.push('    while (*a && *a == *b) { a++; b++; }');
  lines.push('    if (*a == 0 && (*b == 0 || (*b == \'?\' && b[1] == 0))) return &WEB_ASSETS[i];');
  lines.push('  }');
  lines.push('  return nullptr;');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const assets = await buildAssets({ min: args.min });
  const header = renderHeader(assets);
  const outputs = args.out
    ? [args.out]
    : args.min
      ? [join(ROOT, 'firmware/arsin_print_server_esp8266/web_assets.h')]
      : [join(ROOT, 'firmware/arsin_print_server/web_assets.h')];
  for (const out of outputs) {
    await mkdir(dirname(out), { recursive: true });
    await writeFile(out, header);
  }
  const rawTotal = assets.reduce((n, a) => n + a.original, 0);
  const gzTotal = assets.reduce((n, a) => n + a.data.length, 0);
  console.log(`web assets: ${assets.length} files, ${(rawTotal / 1024).toFixed(1)} kB raw -> ${(gzTotal / 1024).toFixed(1)} kB embedded`);
  for (const a of assets) console.log(`  ${a.path.padEnd(34)} ${String(a.original).padStart(7)} B${a.gz ? ` -> ${String(a.data.length).padStart(7)} B gz` : ' (stored raw)'}`);
  for (const out of outputs) console.log(`wrote ${relative(ROOT, out)} (${(header.length / 1024).toFixed(1)} kB of C source)`);
  return { assets, header, outputs };
}

if (process.argv[1] && process.argv[1].endsWith('build-web-assets.mjs')) {
  main().catch((e) => {
    console.error('build-web-assets failed:', e.message);
    process.exit(1);
  });
}
